import { randomUUID } from "node:crypto";
import { existsSync, lstatSync, mkdtempSync, readFileSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const PROJECT_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const GUARD_PATH = path.join(PROJECT_ROOT, "scripts/lib/deny-disposable-env.cjs");
const manifest = JSON.parse(readFileSync(path.join(PROJECT_ROOT, "contracts/runtime/v1/environment.json"), "utf8"));
const SYSTEM_KEYS = ["PATH", "SystemRoot", "WINDIR", "ComSpec", "PATHEXT", "TEMP", "TMP", "HOME", "USERPROFILE", "APPDATA", "LOCALAPPDATA", "HOMEDRIVE", "HOMEPATH", "NUMBER_OF_PROCESSORS", "PROCESSOR_ARCHITECTURE", "COREPACK_HOME", "GOCACHE", "GOMODCACHE", "GOPATH"];

export function assertDisposableTestDatabaseUrl(raw) {
  let url;
  try { url = new URL(raw); } catch { throw new Error("A generated disposable database URL is required"); }
  const databaseUser = /^\/worker_contracts_[a-f0-9]{16}$/.test(url.pathname) ? "worker_contracts"
    : /^\/narra_canvas_(?:full|additive)_[a-f0-9]{16}$/.test(url.pathname) ? "narra_canvas" : null;
  if (url.protocol !== "postgresql:" || url.hostname !== "127.0.0.1" || !/^[1-9][0-9]*$/.test(url.port) || Number(url.port) > 65535
    || databaseUser === null || url.username !== databaseUser || !url.password || url.hash
    || url.searchParams.size !== 2 || url.searchParams.getAll("schema").length !== 1 || url.searchParams.get("schema") !== "public"
    || url.searchParams.getAll("connect_timeout").length !== 1 || url.searchParams.get("connect_timeout") !== "3") {
    throw new Error("Refusing a database not generated by a disposable contracts runner");
  }
  return url;
}

/**
 * @param {string} databaseUrl
 * @param {Record<string, string>} [extra]
 * @param {Record<string, string | undefined>} [source]
 * @returns {NodeJS.ProcessEnv}
 */
export function disposableTestEnvironment(databaseUrl, extra = {}, source = process.env) {
  assertDisposableTestDatabaseUrl(databaseUrl);
  /** @type {NodeJS.ProcessEnv} */
  const env = { NODE_ENV: "test" };
  for (const key of SYSTEM_KEYS) if (source[key] !== undefined) env[key] = source[key];
  for (const variable of manifest.variables) {
    if (variable.name === "NODE_ENV" || variable.name === "APP_URL") continue;
    env[variable.name] = variable.secret || variable.default == null ? "" : String(variable.default);
  }
  Object.assign(env, extra, {
    DATABASE_URL: databaseUrl,
    TEST_DATABASE_URL: databaseUrl,
    AUTH_SECRET: "disposable-canvas-contract-test-only-not-a-real-secret",
    NODE_ENV: "test",
    NODE_OPTIONS: `--require=${JSON.stringify(GUARD_PATH.replaceAll("\\", "/"))}`,
    ENABLE_EMBEDDED_WORKER: "false",
    WORKER_RUNTIME_MODE: "dedicated",
    ENABLE_LOCAL_IMAGE_FALLBACK: "false",
    PRISMA_HIDE_UPDATE_MESSAGE: "1",
    NEXT_TELEMETRY_DISABLED: "1",
  });
  delete env.APP_URL;
  for (const key of Object.keys(env)) if (key.startsWith("S3_")) env[key] = key === "S3_REGION" ? "auto" : "";
  return env;
}

export function createDisposablePrismaWorkspace({ prefix, parent = tmpdir(), migrationsPath = path.join(PROJECT_ROOT, "prisma/migrations") }) {
  if (!/^narra-(?:canvas|worker)-contracts-prisma-$/.test(prefix)) throw new Error("Unsafe disposable scratch prefix");
  const safeParent = realpathSync(path.resolve(parent));
  const directory = mkdtempSync(path.join(safeParent, prefix));
  const ownerToken = randomUUID();
  const ownerPath = path.join(directory, "owner.json");
  writeFileSync(ownerPath, JSON.stringify({ ownerToken }), { flag: "wx" });
  const configPath = path.join(directory, "prisma.config.mjs");
  const configModule = pathToFileURL(path.join(PROJECT_ROOT, "node_modules/prisma/config.js")).href;
  const paths = JSON.stringify({ schema: path.join(PROJECT_ROOT, "prisma/schema.prisma"), migrations: { path: path.resolve(migrationsPath) } });
  writeFileSync(configPath, `import { defineConfig, env } from ${JSON.stringify(configModule)};\nexport default defineConfig({...${paths}, datasource:{url:env("DATABASE_URL")}});\n`);
  return { directory, configPath, ownerToken, safeParent };
}

export function cleanupDisposablePrismaWorkspace(workspace) {
  if (!workspace) return true;
  const resolved = path.resolve(workspace.directory);
  const same = (a, b) => process.platform === "win32" ? a.toLowerCase() === b.toLowerCase() : a === b;
  if (!same(path.dirname(resolved), workspace.safeParent) || !/^narra-(?:canvas|worker)-contracts-prisma-[A-Za-z0-9]+$/.test(path.basename(resolved))) return false;
  if (!existsSync(resolved)) return true;
  try {
    if (lstatSync(resolved).isSymbolicLink() || !same(realpathSync(resolved), resolved) || JSON.parse(readFileSync(path.join(resolved, "owner.json"), "utf8")).ownerToken !== workspace.ownerToken) return false;
    rmSync(resolved, { recursive: true, force: true });
    return !existsSync(resolved);
  } catch { return false; }
}
